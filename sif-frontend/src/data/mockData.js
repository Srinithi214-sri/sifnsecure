const SIF = 'SIF precursor';
const NOT_SIF = 'Not SIF';

// Work out the verdict from the scores and energy
function withVerdicts(report) {
  const exceedsThreshold = report.eei.energyFtLbs !== null && report.eei.energyFtLbs > EEI_THRESHOLD_FT_LBS;
  const mlVerdict = report.sifScore >= ML_SIF_THRESHOLD ? SIF : NOT_SIF;
  const eeiVerdict = exceedsThreshold ? SIF : NOT_SIF;
  return {
    ...report,
    eei: { ...report.eei, exceedsThreshold },
    mlVerdict,
    eeiVerdict,
    agree: mlVerdict === eeiVerdict,
  };
}

